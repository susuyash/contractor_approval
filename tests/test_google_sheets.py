def test_sync_all_to_google_sheets_writes_summary_and_history(monkeypatch):
    service = MagicMock()
    workbook = {
        "sheets": [
            {"properties": {"title": "Sheet1", "sheetId": 1}},
            {"properties": {"title": "Participants", "sheetId": 2}},
            {"properties": {"title": "Messages", "sheetId": 3}},
            {"properties": {"title": "Cases", "sheetId": 4}},
            {"properties": {"title": "Case History", "sheetId": 5}},
        ]
    }

    def mock_batch_update(*args, **kwargs):
        body = kwargs.get("body", {})
        for request in body.get("requests", []):
            if "deleteSheet" in request:
                sheet_id = request["deleteSheet"]["sheetId"]
                workbook["sheets"] = [
                    sheet for sheet in workbook["sheets"]
                    if sheet.get("properties", {}).get("sheetId") != sheet_id
                ]
        return MagicMock()

    service.spreadsheets().get().execute.side_effect = lambda *args, **kwargs: workbook
    service.spreadsheets().batchUpdate.side_effect = mock_batch_update
    spreadsheet_id = "spreadsheet-123"

    cases = [
        {
            "id": f"case-{case_number}",
            "covering_number": str(case_number),
            "description": "Payment request",
            "first_seen": "2026-08-01T09:00:00Z",
            "updated_at": "2026-08-02T00:00:00Z",
        }
        for case_number in range(2000, 2200)
    ]
    participants = [
        {"case_id": f"case-{case_number}", "person": "Mukesh", "status": "APPROVED"}
        for case_number in range(2000, 2200)
    ]
    messages = [
        {
            "case_id": f"case-{case_number}",
            "timestamp": "2026-08-01T09:00:00Z",
            "sender": "Utpal Singh",
            "message": f"Case {case_number} generated",
        }
        for case_number in range(2000, 2200)
    ]
    database_client = object()
    used_clients = []
    read_counts = {"cases": 0, "participants": 0, "messages": 0}

    def get_cases_once(client):
        read_counts["cases"] += 1
        used_clients.append(client)
        return cases

    def get_participants_once(client, all_cases):
        assert all_cases is True
        read_counts["participants"] += 1
        used_clients.append(client)
        return participants

    def get_messages_once(client, all_cases):
        assert all_cases is True
        read_counts["messages"] += 1
        used_clients.append(client)
        return messages

    monkeypatch.setenv("GOOGLE_SHEETS_SPREADSHEET_ID", spreadsheet_id)
    monkeypatch.setattr("google_sheets.get_supabase_client", lambda: database_client)
    monkeypatch.setattr("google_sheets.get_cases", get_cases_once)
    monkeypatch.setattr("google_sheets.get_participants", get_participants_once)
    monkeypatch.setattr("google_sheets.get_messages", get_messages_once)
    monkeypatch.setattr("google_sheets.get_sheets_service", lambda: service)
    monkeypatch.setattr("google_sheets._legacy_cleanup_checked", False)

    sync_all_to_google_sheets()

    assert used_clients == [database_client, database_client, database_client]
    assert read_counts == {"cases": 1, "participants": 1, "messages": 1}
    assert service.spreadsheets().batchUpdate.call_count >= 2
    assert service.spreadsheets().values().update.call_count >= 2

    sheet_names = []
    delete_requests = []
    for call in service.spreadsheets().batchUpdate.call_args_list:
        body = call.kwargs.get("body", {})
        requests = body.get("requests", [])
        for request in requests:
            if "deleteSheet" in request:
                delete_requests.append(request)

    assert delete_requests
    assert CASE_SHEET_NAME == "Cases"
    assert CASE_HISTORY_SHEET_NAME == "Case History"


@pytest.mark.parametrize("failure", [RuntimeError("write failed"), TimeoutError("write timed out")])
def test_sheet_write_failure_does_not_clear_existing_values(monkeypatch, failure):
    service = MagicMock()
    service.spreadsheets().get().execute.return_value = {
        "sheets": [{"properties": {"title": "Cases", "sheetId": 4}}]
    }
    service.spreadsheets().values().get().execute.return_value = {"values": [["old header"], ["old case"]]}
    service.spreadsheets().values().update.return_value.execute.side_effect = failure

    from google_sheets import _write_rows_to_sheet

    with pytest.raises(type(failure)):
        _write_rows_to_sheet(service, "spreadsheet-123", "Cases", [["new header"], ["new case"]])

    service.spreadsheets().values().update.assert_called_once()
    service.spreadsheets().values().clear.assert_not_called()


def test_tail_trim_timeout_happens_after_replacement_write():
    service = MagicMock()
    service.spreadsheets().get().execute.return_value = {
        "sheets": [{"properties": {"title": "Cases", "sheetId": 4}}]
    }
    values_api = service.spreadsheets().values()
    values_api.get.return_value.execute.return_value = {"values": [["old"]] * 5}
    values_api.clear.return_value.execute.side_effect = TimeoutError("trim timed out")

    from google_sheets import _write_rows_to_sheet

    with pytest.raises(TimeoutError, match="trim timed out"):
        _write_rows_to_sheet(service, "spreadsheet-123", "Cases", [["new header"], ["new row"]])

    method_names = [call[0] for call in values_api.method_calls]
    assert method_names.index("update") < method_names.index("clear")


