def test_case_history_uses_fifth_approval_timestamp_and_pending_has_no_fake_finalization():
    case = {"covering_number": "259", "description": "Payment request", "first_seen": "2026-08-01T09:00:00Z"}
    first_approval_messages = [
        {"timestamp": "2026-08-01T09:05:00Z", "sender": "Utpal Singh", "text": "Case 259 opened"},
        {"timestamp": "2026-08-01T09:10:00Z", "sender": "Mukesh", "text": "Approved"},
        {"timestamp": "2026-08-01T09:15:00Z", "sender": "Mehta Ji SPM Dv Bsp Site", "text": "Approved"},
        {"timestamp": "2026-08-01T09:20:00Z", "sender": "Jagga Rao Sir", "text": "Approved"},
        {"timestamp": "2026-08-01T09:25:00Z", "sender": "Gagan Deep Singh", "text": "Approved"},
        {"timestamp": "2026-08-01T09:30:00Z", "sender": "Deep Patel Sir", "text": "Approved"},
    ]

    rows = build_case_history_rows(case, first_approval_messages)
    flattened = "\n".join(str(cell) for row in rows for cell in row if cell is not None)

    assert "CASE NO: 259" in flattened
    assert "Generated by: Utpal Singh" in flattened
    assert "Time: 15:00" in flattened
    assert "Status: APPROVED" in flattened
    assert "Date: 01-08-26" in flattened

    pending_case = {"covering_number": "261", "description": "Pending case", "first_seen": "2026-08-01T10:00:00Z"}
    pending_rows = build_case_history_rows(pending_case, [
        {"timestamp": "2026-08-01T10:02:00Z", "sender": "Utpal Singh", "text": "Case 261 opened"},
        {"timestamp": "2026-08-01T10:05:00Z", "sender": "Mukesh", "text": "Approved"},
    ])
    pending_flattened = "\n".join(str(cell) for row in pending_rows for cell in row if cell is not None)
    assert "Status: PENDING" in pending_flattened
    assert "Finalized:" not in pending_flattened or "Date:" not in pending_flattened.split("Finalized:")[-1]


